// @vitest-environment node
import { afterAll, beforeAll, beforeEach, describe, expect, it } from "vitest";
import type { Order } from "../../../server/src/domain/order.js";
import { validInput as valid } from "../../support/fixtures.js";
import { createTestApp, type TestApp } from "../../support/testApp.js";

let stack: TestApp;

// One in-memory Postgres (PGlite) per file, reset to the seed data before every test.
beforeAll(async () => {
    stack = await createTestApp();
});

beforeEach(() => stack.reset());

afterAll(() => stack.close());

type Method = "GET" | "POST" | "PUT" | "PATCH" | "DELETE";
const get = (url: string) => stack.app.inject({ method: "GET", url });
const send = (method: Method, url: string, payload?: Record<string, unknown>) => stack.app.inject({ method, url, payload });

describe("GET /api/orders", () => {
    it("returns the seeded orders with the API field names and numeric types", async () => {
        const response = await get("/api/orders");
        const orders: Order[] = response.json();

        expect(response.statusCode).toBe(200);
        expect(orders).toHaveLength(24);
        expect(orders[0]).toEqual({
            id: 1,
            code: "OS-2026-001",
            client: "Distribuidora La Ceiba",
            taxId: "1234567-8",
            department: "Guatemala",
            category: "preventive_maintenance",
            technician: "Mario Ixcot",
            date: "2026-01-14",
            hours: 3.5,
            amount: 1750,
            status: "completed",
        });
        expect(orders.map((o) => o.id)).toEqual([...orders.map((o) => o.id)].sort((a, b) => a - b));
    });

    it("does not expose internal columns", async () => {
        const [order] = (await get("/api/orders")).json();
        expect(order).not.toHaveProperty("createdAt");
        expect(order).not.toHaveProperty("created_at");
    });
});

describe("GET /api/orders/:id", () => {
    it("returns one order", async () => {
        const response = await get("/api/orders/2");
        expect(response.statusCode).toBe(200);
        expect(response.json().id).toBe(2);
    });

    it("404s for an order that does not exist", async () => {
        const response = await get("/api/orders/9999");
        expect(response.statusCode).toBe(404);
        expect(response.json().message).toBe("Orden no encontrada.");
    });

    it("400s for an id that is not a positive integer", async () => {
        for (const id of ["abc", "0", "-3", "1.5"]) {
            expect((await get(`/api/orders/${id}`)).statusCode).toBe(400);
        }
    });
});

describe("POST /api/orders", () => {
    it("creates a pending order whose code is generated by the server", async () => {
        const response = await send("POST", "/api/orders", valid);

        expect(response.statusCode).toBe(201);
        expect(response.json()).toMatchObject({ ...valid, id: 25, status: "pending" });
        expect(response.json().code).toBe(`OS-${new Date().getFullYear()}-025`);
        expect((await get("/api/orders/25")).statusCode).toBe(200);
    });

    it("ignores id, code and status sent by the client", async () => {
        const response = await send("POST", "/api/orders", { ...valid, id: 1, code: "HACK", status: "completed" });

        expect(response.statusCode).toBe(201);
        expect(response.json()).toMatchObject({ id: 25, status: "pending" });
        expect(response.json().code).not.toBe("HACK");
    });

    it("normalizes the NIT and trims text", async () => {
        const response = await send("POST", "/api/orders", { ...valid, taxId: " cf ", client: "  Hotel  " });
        expect(response.json()).toMatchObject({ taxId: "CF", client: "Hotel" });
    });

    it("gives concurrent creates distinct ids and codes", async () => {
        const responses = await Promise.all(Array.from({ length: 6 }, () => send("POST", "/api/orders", valid)));
        const codes = responses.map((r) => r.json().code);

        expect(responses.every((r) => r.statusCode === 201)).toBe(true);
        expect(new Set(codes).size).toBe(6);
    });

    it("rejects an invalid body with a Spanish message and the list of issues", async () => {
        const response = await send("POST", "/api/orders", { ...valid, client: "", hours: 30 });

        expect(response.statusCode).toBe(400);
        expect(response.json().message).toBe("Cliente obligatorio.");
        expect(response.json().issues.map((i: { path: string }) => i.path)).toEqual(["client", "hours"]);
    });

    it.each<[string, unknown]>([
        ["taxId", "abc"],
        ["department", "Narnia"],
        ["category", "magic"],
        ["date", "14/10/2026"],
        ["date", "2026-13-45"],
        ["date", "2026-02-31"],
        ["date", "2026-04-31"],
        ["hours", 0],
        ["hours", "4"],
        ["amount", -5],
        ["amount", "150"],
        ["amount", 1e12],
    ])("rejects %s = %j", async (field, value) => {
        const response = await send("POST", "/api/orders", { ...valid, [field]: value });
        expect(response.statusCode).toBe(400);
    });

    it("rejects a missing body", async () => {
        expect((await send("POST", "/api/orders")).statusCode).toBe(400);
    });

    it("does not create anything when validation fails", async () => {
        await send("POST", "/api/orders", { ...valid, client: "" });
        expect((await get("/api/orders")).json()).toHaveLength(24);
    });
});

describe("PUT /api/orders/:id", () => {
    it("replaces the editable fields and keeps id and code", async () => {
        const response = await send("PUT", "/api/orders/1", { ...valid, status: "in_progress", id: 99, code: "HACK" });

        expect(response.statusCode).toBe(200);
        expect(response.json()).toMatchObject({ ...valid, id: 1, code: "OS-2026-001", status: "in_progress" });
    });

    it("keeps the stored status when the body has none, so a stale edit cannot undo a status change", async () => {
        await send("PATCH", "/api/orders/1", { status: "cancelled" });

        const response = await send("PUT", "/api/orders/1", { ...valid });

        expect(response.statusCode).toBe(200);
        expect(response.json()).toMatchObject({ ...valid, id: 1, status: "cancelled" });
    });

    it("404s for an unknown order and 400s for an invalid body or status", async () => {
        expect((await send("PUT", "/api/orders/9999", { ...valid })).statusCode).toBe(404);
        expect((await send("PUT", "/api/orders/1", { ...valid, client: "" })).statusCode).toBe(400);
        expect((await send("PUT", "/api/orders/1", { ...valid, status: "flying" })).statusCode).toBe(400);
    });
});

describe("PATCH /api/orders/:id", () => {
    it("changes only the status", async () => {
        const before = (await get("/api/orders/3")).json();
        const response = await send("PATCH", "/api/orders/3", { status: "cancelled" });

        expect(response.statusCode).toBe(200);
        expect(response.json()).toEqual({ ...before, status: "cancelled" });
    });

    it("rejects an unknown status and does not change the order", async () => {
        const before = (await get("/api/orders/3")).json();
        expect((await send("PATCH", "/api/orders/3", { status: "flying" })).statusCode).toBe(400);
        expect((await get("/api/orders/3")).json()).toEqual(before);
    });

    it("404s for an unknown order", async () => {
        expect((await send("PATCH", "/api/orders/9999", { status: "completed" })).statusCode).toBe(404);
    });
});

describe("DELETE /api/orders/:id", () => {
    it("deletes with 204 and no body, then the order is gone", async () => {
        const response = await send("DELETE", "/api/orders/4");

        expect(response.statusCode).toBe(204);
        expect(response.body).toBe("");
        expect((await get("/api/orders/4")).statusCode).toBe(404);
        expect((await get("/api/orders")).json()).toHaveLength(23);
    });

    it("404s the second time", async () => {
        await send("DELETE", "/api/orders/4");
        expect((await send("DELETE", "/api/orders/4")).statusCode).toBe(404);
    });

    it("does not reuse the id of a deleted order for the next one", async () => {
        const last = (await get("/api/orders")).json().at(-1).id;
        await send("DELETE", `/api/orders/${last}`);
        expect((await send("POST", "/api/orders", valid)).json().id).toBe(last + 1);
    });
});

describe("platform", () => {
    it("serves a health check", async () => {
        expect((await get("/api/health")).json()).toEqual({ status: "ok" });
    });

    it("answers unknown routes with a JSON 404", async () => {
        const response = await get("/api/nope");
        expect(response.statusCode).toBe(404);
        expect(response.json().message).toBe("Ruta no encontrada.");
    });

    it("sends CORS headers so the dev front end on another port can call it", async () => {
        const response = await stack.app.inject({ method: "GET", url: "/api/orders", headers: { origin: "http://localhost:5173" } });
        expect(response.headers["access-control-allow-origin"]).toBe("http://localhost:5173");
    });

    it.each(["PUT", "PATCH", "DELETE"])("answers the browser preflight for %s", async (method) => {
        const response = await stack.app.inject({
            method: "OPTIONS",
            url: "/api/orders/1",
            headers: {
                origin: "http://localhost:5173",
                "access-control-request-method": method,
                "access-control-request-headers": "content-type",
            },
        });

        expect(response.statusCode).toBe(204);
        expect(response.headers["access-control-allow-methods"]).toContain(method);
        expect(response.headers["access-control-allow-headers"]).toContain("content-type");
    });
});

describe("failed requests", () => {
    it("do not burn an order number", async () => {
        await send("POST", "/api/orders", { ...valid, date: "2026-02-31" });
        await send("POST", "/api/orders", { ...valid, amount: 1e12 });

        expect((await send("POST", "/api/orders", valid)).json().id).toBe(25);
    });
});

describe("accepts the last day of a leap year and rejects Feb 29 otherwise", () => {
    it.each<[string, number]>([["2028-02-29", 201], ["2026-02-29", 400]])("date %s -> %i", async (date, status) => {
        expect((await send("POST", "/api/orders", { ...valid, date })).statusCode).toBe(status);
    });
});
